-- Kladen metadata schema for Oracle Autonomous DB (run as ADMIN, or as a
-- dedicated KLADEN schema user). Mirrors backend/api.py's SQLite model plus
-- dual-mode profiles (manual vs vault) and object-storage artifact pointers.
--
-- Timestamps and summary_json are VARCHAR2, not TIMESTAMP/CLOB, on purpose:
-- the app stores ISO-8601 UTC strings and small JSON text, so keeping these as
-- VARCHAR2 lets one set of SQL run unchanged on both SQLite and Oracle (no
-- datetime binding or LOB handling). created_at defaults to an ISO UTC string.
--
-- What lives here (metadata only): orgs, clients, stacks, runs, profiles as
-- POINTERS, users, approvals. Blobs (logs, plan.json, reports, state, keys)
-- live in Object Storage / Vault; this DB stores only their locations.
--
-- Idempotent-ish: drops are commented so a re-run doesn't wipe data. Uncomment
-- the DROP block for a clean rebuild.

